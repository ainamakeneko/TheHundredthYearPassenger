document.addEventListener("keydown", (event) => {
  if (dom.game.hidden || dom.notes.open || dom.restartDialog.open) return;
  if (event.key === "Escape" && !dom.commandPanel.hidden) {
    event.preventDefault();
    closeCommandPanel();
    return;
  }
  if (event.key === " " || event.key === "Enter") {
    event.preventDefault();
    if (prologueActive) advancePrologue();
    else if (!dom.chapterCard.hidden) continueFromChapterCard();
    else advanceDialogue();
    return;
  }
  const index = Number(event.key) - 1;
  if (index >= 0 && index < dom.verbs.length && !dialogueBusy && !prologueActive && !state.finished) {
    setActiveVerb(dom.verbs[index].dataset.verb);
    openCommandPanel();
    showCommandLevel("targets");
  }
});

