async function startAmbient() {
  if (soundOn || soundPending) return;
  soundPending = true;
  dom.sound.textContent = "JAZZ …";
  dom.sound.removeAttribute("title");

  try {
    dom.jazzPlayer.muted = false;
    dom.jazzPlayer.volume = 0.72;
    await dom.jazzPlayer.play();
    soundOn = true;
    dom.sound.textContent = "JAZZ ON";
    dom.sound.setAttribute("aria-pressed", "true");
  } catch (error) {
    soundOn = false;
    dom.sound.textContent = "JAZZ 再試行";
    dom.sound.setAttribute("aria-pressed", "false");
    dom.sound.setAttribute("title", "音声を再生できませんでした。もう一度押してください。");
    console.warn("Jazz playback failed", error);
  } finally {
    soundPending = false;
  }
}

function stopAmbient() {
  dom.jazzPlayer.pause();
  soundPending = false;
  soundOn = false;
  dom.sound.textContent = "JAZZ OFF";
  dom.sound.setAttribute("aria-pressed", "false");
}

