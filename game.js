function getCaseSnapshot() {
  if (!dom.title.hidden) {
    return {
      screen: "title",
      canContinue: Boolean(loadSavedState())
    };
  }
  if (state.finished) {
    return {
      screen: "ending",
      observations: getLookCount(),
      totalObservations: getLookTotal()
    };
  }
  if (prologueActive) {
    const slide = prologueSlides[prologueIndex];
    return {
      screen: "prologue",
      step: prologueIndex + 1,
      totalSteps: prologueSlides.length,
      title: slide.title,
      text: slide.text,
      canAdvance: true
    };
  }
  const scene = sceneById[state.currentScene];
  const targets = (scene.actions[activeVerb] || [])
    .filter(targetIsAvailable)
    .map((target) => ({ id: target.id, label: target.label, seen: state.seen.includes(seenKey(scene.id, activeVerb, target.id)) }));
  if (activeVerb === "move") {
    targets.push({ id: "next", label: scene.nextLabel, locked: !isSceneReady(scene) });
  }
  return {
    screen: "game",
    sceneId: scene.id,
    location: scene.location,
    activeVerb,
    dialogueBusy,
    currentDialogue: dom.dialogueText.textContent,
    targets,
    observations: getLookCount(),
    totalObservations: getLookTotal()
  };
}

function registerWebMCPTools() {
  const context = typeof document === "undefined" ? undefined : document.modelContext;
  if (!context?.registerTool) return;
  const lifecycle = new AbortController();
  const report = (error) => console.warn("WebMCP registration failed", error);
  const register = (tool) => {
    try {
      void Promise.resolve(context.registerTool(tool, { signal: lifecycle.signal })).catch(report);
    } catch (error) {
      report(error);
    }
  };

  register({
    name: "read_case_state",
    title: "捜査状況を読む",
    description: "現在の画面、場所、選択中のコマンド、選べる対象、観察数を読み取ります。状態は変更しません。",
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
    annotations: { readOnlyHint: true, untrustedContentHint: false },
    execute() {
      return getCaseSnapshot();
    }
  });

  register({
    name: "start_case",
    title: "捜査を開始する",
    description: "新しい捜査を開始するか、保存済みの捜査を再開して、ゲーム画面を表示します。",
    inputSchema: {
      type: "object",
      properties: { mode: { type: "string", enum: ["new", "continue"] } },
      required: ["mode"],
      additionalProperties: false
    },
    annotations: { readOnlyHint: false, untrustedContentHint: false },
    execute(input) {
      if (!input || (input.mode !== "new" && input.mode !== "continue")) throw new Error("mode must be new or continue");
      if (input.mode === "continue" && !loadSavedState()) throw new Error("No saved case is available");
      beginGame(input.mode === "continue");
      return getCaseSnapshot();
    }
  });

  register({
    name: "choose_case_action",
    title: "捜査コマンドを選ぶ",
    description: "「見る」「話す」「考える」「移動する」の対象を一つ選び、画面上でも同じ行動を実行します。targetId は read_case_state の targets から選びます。",
    inputSchema: {
      type: "object",
      properties: {
        verb: { type: "string", enum: ["look", "talk", "think", "move"] },
        targetId: { type: "string", minLength: 1 }
      },
      required: ["verb", "targetId"],
      additionalProperties: false
    },
    annotations: { readOnlyHint: false, untrustedContentHint: false },
    execute(input) {
      if (!input || !verbLabels[input.verb] || typeof input.targetId !== "string") throw new Error("Invalid action");
      if (!dom.title.hidden || state.finished) throw new Error("The case is not on an active scene");
      if (prologueActive) throw new Error("Advance the prologue before choosing an investigation action");
      if (dialogueBusy) throw new Error("Advance the current dialogue before choosing another action");
      const scene = sceneById[state.currentScene];
      setActiveVerb(input.verb);
      if (input.verb === "move" && input.targetId === "next") {
        if (!isSceneReady(scene)) throw new Error(scene.hint);
        if (scene.next === "ending") showEnding();
        else if (scene.next === "prototype_end") showPrototypeEnd();
        else loadScene(scene.next);
        return getCaseSnapshot();
      }
      const target = (scene.actions[input.verb] || []).find((item) => item.id === input.targetId && targetIsAvailable(item));
      if (!target) throw new Error("Target is not available in the current scene");
      selectTarget(target, input.verb);
      return getCaseSnapshot();
    }
  });

  register({
    name: "advance_case_dialogue",
    title: "文章を送る",
    description: "導入、章扉、または表示中の台詞を次へ進めます。",
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
    annotations: { readOnlyHint: false, untrustedContentHint: false },
    execute() {
      if (prologueActive) advancePrologue();
      else if (!dom.chapterCard.hidden) continueFromChapterCard();
      else if (!dialogueBusy) throw new Error("No text is waiting");
      else advanceDialogue();
      return getCaseSnapshot();
    }
  });
}

