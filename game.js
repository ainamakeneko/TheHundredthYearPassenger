function freshState() {
  return {
    currentScene: "dock",
    seen: [],
    flags: [],
    readyScenes: [],
    visitedScenes: [],
    prologueSeen: false,
    finished: false,
    startedAt: Date.now()
  };
}

function hasFlag(flag) {
  return state.flags.includes(flag);
}

function addFlag(flag) {
  if (flag && !hasFlag(flag)) state.flags.push(flag);
}

function seenKey(sceneId, verb, id) {
  return `${sceneId}:${verb}:${id}`;
}

function isSceneReady(scene) {
  return scene.required.every(hasFlag);
}

function getLookTotal() {
  return scenes
    .filter((scene) => playableSceneIds.has(scene.id))
    .reduce((sum, scene) => sum + scene.actions.look.length, 0);
}

function getLookCount() {
  return state.seen.filter((key) => playableSceneIds.has(key.split(":")[0]) && key.split(":")[1] === "look").length;
}

function sanitizeLoadedState(value) {
  const base = freshState();
  if (!value || typeof value !== "object") return base;
  const currentScene = sceneById[value.currentScene] ? value.currentScene : "dock";
  return {
    currentScene,
    seen: Array.isArray(value.seen) ? value.seen.filter((item) => typeof item === "string") : [],
    flags: Array.isArray(value.flags) ? value.flags.filter((item) => typeof item === "string") : [],
    readyScenes: Array.isArray(value.readyScenes) ? value.readyScenes.filter((item) => sceneById[item]) : [],
    visitedScenes: Array.isArray(value.visitedScenes) ? value.visitedScenes.filter((item) => sceneById[item]) : [],
    prologueSeen: value.prologueSeen === undefined ? true : Boolean(value.prologueSeen),
    finished: Boolean(value.finished),
    startedAt: Number(value.startedAt) || Date.now()
  };
}

function loadSavedState() {
  try {
    const raw = localStorage.getItem(saveKey);
    return raw ? sanitizeLoadedState(JSON.parse(raw)) : null;
  } catch {
    return null;
  }
}

function saveState() {
  try {
    localStorage.setItem(saveKey, JSON.stringify(state));
    dom.autosave.classList.add("is-saving");
    dom.autosave.textContent = "SAVED";
    window.setTimeout(() => {
      dom.autosave.classList.remove("is-saving");
      dom.autosave.textContent = "AUTOSAVE";
    }, 800);
  } catch {
    dom.autosave.textContent = "SAVE UNAVAILABLE";
  }
}

