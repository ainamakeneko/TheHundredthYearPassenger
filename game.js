function loadScene(sceneId, options = {}) {
  const scene = sceneById[sceneId];
  if (!scene) return;
  state.currentScene = sceneId;
  const firstVisit = !state.visitedScenes.includes(sceneId);
  if (firstVisit) state.visitedScenes.push(sceneId);

  dom.chapter.textContent = scene.chapter;
  dom.location.textContent = scene.location;
  dom.time.textContent = scene.time;
  dom.sceneCode.textContent = scene.code;
  dom.sceneWord.textContent = scene.word;
  dom.sceneEyebrow.textContent = scene.eyebrow;
  dom.sceneHeading.textContent = scene.location;
  dom.sceneCaption.textContent = scene.caption;
  dom.sceneArt.style.setProperty("--scene-accent", scene.accent);
  const backgroundKey = sceneBackgrounds[scene.id] || "dock";
  dom.sceneBackdrop.style.setProperty("--scene-image", `url("${visualAssets[backgroundKey]}")`);
  dom.sceneBackdrop.setAttribute("aria-label", `${scene.location}の無人の風景`);
  dom.sceneArt.classList.remove("is-background-focus", "is-prologue");
  prologueActive = false;
  dom.prologuePanel.hidden = true;
  hideSpeakerStage();
  dom.inspectionWindow.hidden = true;
  dom.chapterCard.hidden = true;
  dom.gameLayout.hidden = false;
  dom.dialoguePanel.hidden = false;
  dom.ending.hidden = true;

  setActiveVerb("look");
  updateCounts();
  saveState();

  if (options.prologue) {
    showPrologue(0);
  } else if (firstVisit && !options.resume) {
    const sceneIndex = scenes.findIndex((item) => item.id === scene.id);
    showChapterCard({
      number: scene.id === "office" ? "FINAL CHAPTER" : `CHAPTER ${String(sceneIndex + 1).padStart(2, "0")}`,
      title: scene.chapter,
      place: `${scene.location}｜${scene.time}`,
      button: "この章を始める"
    }, scene.intro);
  } else {
    startDialogue([scene.resume]);
  }
}

