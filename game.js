function setSprite(element, assetKey, position, size = "200% 200%") {
  element.style.backgroundImage = `url("${visualAssets[assetKey]}")`;
  element.style.backgroundSize = size;
  element.style.backgroundPosition = position.join(" ");
}

function getTargetVisual(target, verb) {
  const storySprite = storyObjectSprites[`${state.currentScene}:${target.id}`];
  if (storySprite) return { ...storySprite, size: "300% 300%" };
  if (state.currentScene === "dock" && objectSprites[target.id]) return { asset: "objects", position: objectSprites[target.id], size: "300% 300%" };
  if (state.currentScene === "dock" && reactionSprites[target.id]) return { asset: "reactions", position: reactionSprites[target.id], size: "200% 200%" };
  if (state.currentScene === "dock" && personSprites[target.id]) return { asset: "people", position: personSprites[target.id], size: "200% 200%" };
  if (verb === "think") return { asset: "people", position: ["0%", "0%"], size: "200% 200%" };
  if (target.id === "walk_pier" || target.id === "why_return" || target.id === "281") {
    return { asset: "objects", position: objectSprites.elpis, size: "300% 300%" };
  }
  if (target.id === "under_awning") {
    return { asset: "objects", position: objectSprites.streetlamp, size: "300% 300%" };
  }
  return { asset: sceneBackgrounds[state.currentScene] || "dock", position: ["50%", "50%"], size: "cover" };
}

function showInspection(target, verb) {
  const visual = getTargetVisual(target, verb);
  setSprite(dom.inspectionImage, visual.asset, visual.position, visual.size);
  const number = [...(sceneById[state.currentScene].actions[verb] || [])].findIndex((item) => item.id === target.id) + 1;
  dom.inspectionKind.textContent = verb === "look" ? "OBSERVATION" : verb === "talk" ? "SUBJECT" : verb === "think" ? "DEDUCTION" : "LOCATION";
  dom.inspectionNumber.textContent = String(Math.max(number, 1)).padStart(2, "0");
  dom.inspectionLabel.textContent = target.label;
  dom.inspectionImage.setAttribute("aria-label", `${target.label}の画像`);
  hideSpeakerStage();
  dom.inspectionWindow.hidden = verb === "talk";
  dom.inspectionWindow.classList.remove("is-entering");
  void dom.inspectionWindow.offsetWidth;
  dom.inspectionWindow.classList.add("is-entering");
}

function updateSpeakerPortrait(speaker) {
  const sprite = speakerSprites[speaker];
  if (!sprite) {
    dom.speakerPortrait.hidden = true;
    hideSpeakerStage();
    return;
  }

  dom.speakerPortrait.hidden = false;
  setSprite(dom.speakerPortrait, "speakerAtlas", sprite.position, "300% 300%");
  dom.speakerPortrait.setAttribute("aria-label", speaker);

  const keepInspectionClear = speaker === "ヴァン・レイ" && !dom.inspectionWindow.hidden && activeVerb !== "talk";
  if (keepInspectionClear) {
    hideSpeakerStage();
    return;
  }

  setSprite(dom.speakerStageImage, "speakerAtlas", sprite.position, "300% 300%");
  dom.speakerStageImage.setAttribute("aria-label", speaker);
  dom.speakerStageLabel.textContent = speaker;
  dom.speakerStage.classList.toggle("is-left", sprite.side === "left");
  dom.speakerStage.classList.toggle("is-right", sprite.side !== "left");
  dom.speakerStage.hidden = false;
  dom.sceneArt.classList.add("has-speaker");
}

function setActiveVerb(verb) {
  activeVerb = verb;
  dom.verbs.forEach((button) => {
    const active = button.dataset.verb === verb;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  dom.targetLabel.textContent = verbLabels[verb];
  dom.commandCurrent.textContent = verbLabels[verb];
  dom.targetHint.textContent = verb === "move" ? "行き先を選ぶ" : "気になるものを選ぶ";
  renderTargets();
}

function targetIsAvailable(target) {
  if (!target.condition) return true;
  const conditions = Array.isArray(target.condition) ? target.condition : [target.condition];
  return conditions.every(hasFlag);
}

function renderTargets() {
  const scene = sceneById[state.currentScene];
  dom.commandToggle.disabled = dialogueBusy || prologueActive || state.finished;
  dom.verbs.forEach((button) => { button.disabled = dialogueBusy || prologueActive || state.finished; });
  if (!scene || state.finished) return;
  dom.targetList.replaceChildren();

  const targets = (scene.actions[activeVerb] || []).filter(targetIsAvailable);
  targets.forEach((target) => {
    const key = seenKey(scene.id, activeVerb, target.id);
    const button = document.createElement("button");
    button.type = "button";
    button.className = "target-button";
    if (state.seen.includes(key)) button.classList.add("is-seen");
    button.disabled = dialogueBusy || prologueActive;
    button.textContent = target.label;
    button.addEventListener("click", () => {
      closeCommandPanel(false);
      selectTarget(target, activeVerb);
    });
    dom.targetList.append(button);
  });

  if (activeVerb === "move") {
    const nextButton = document.createElement("button");
    const ready = isSceneReady(scene);
    nextButton.type = "button";
    nextButton.className = `target-button is-next${ready ? "" : " is-locked"}`;
    nextButton.disabled = dialogueBusy || prologueActive;
    const label = document.createTextNode(scene.nextLabel);
    const small = document.createElement("small");
    small.textContent = ready ? "捜査を進める" : "まだ気になることがある";
    nextButton.append(label, small);
    nextButton.addEventListener("click", () => {
      closeCommandPanel(false);
      if (!ready) {
        startDialogue([line("ヴァン・レイ", scene.hint)]);
        return;
      }
      if (scene.next === "ending") {
        showEnding();
      } else if (scene.next === "prototype_end") {
        showPrototypeEnd();
      } else {
        loadScene(scene.next);
      }
    });
    dom.targetList.append(nextButton);
  }

  if (!dom.targetList.children.length) {
    const empty = document.createElement("p");
    empty.className = "empty-targets";
    empty.textContent = "今は選べる対象がない。";
    dom.targetList.append(empty);
  }
}

function selectTarget(target, verb) {
  if (dialogueBusy || prologueActive) return;
  const scene = sceneById[state.currentScene];
  showInspection(target, verb);
  const key = seenKey(scene.id, verb, target.id);
  const wasSeen = state.seen.includes(key);
  if (!wasSeen) {
    state.seen.push(key);
    addFlag(target.flag);
  }

  let entries = target.lines;
  if (!entries || !entries.length) {
    if (verb === "talk") entries = [line(target.label, "もう話すことはなさそうだ。沈黙にも二度目がある。")];
    else if (verb === "move") entries = [line("ヴァン・レイ", "同じ場所をもう一度歩く。景色は変わらない。見ているものが変わるだけだ。")];
    else entries = [line("ヴァン・レイ", "もう一度見る。物は変わらない。目の方が少しだけしつこくなった。")];
  }

  if (!state.readyScenes.includes(scene.id) && isSceneReady(scene)) {
    state.readyScenes.push(scene.id);
    pendingIntertitle = {
      card: scene.transition,
      entries: scene.readyLines
    };
  }

  updateCounts();
  saveState();
  startDialogue(entries);
}

function startDialogue(entries) {
  if (!entries || !entries.length) return;
  clearTyping();
  closeCommandPanel(false);
  dom.sceneArt.classList.remove("is-background-focus");
  dom.dialoguePanel.hidden = false;
  dialogueQueue = entries.map((entry) => typeof entry === "string" ? line("ヴァン・レイ", entry) : entry);
  dialogueBusy = true;
  renderTargets();
  showNextDialogue();
}

function showNextDialogue() {
  clearTyping();
  if (!dialogueQueue.length) {
    if (pendingIntertitle) {
      const intertitle = pendingIntertitle;
      pendingIntertitle = null;
      showChapterCard(intertitle.card, intertitle.entries);
      return;
    }
    dialogueBusy = false;
    dom.dialoguePanel.classList.remove("is-typing");
    hideSpeakerStage();
    renderTargets();
    return;
  }

  const entry = dialogueQueue.shift();
  dom.speaker.textContent = entry.speaker || "ヴァン・レイ";
  updateSpeakerPortrait(entry.speaker || "ヴァン・レイ");
  fullDialogueText = entry.text || "";
  typingIndex = 0;
  dom.dialogueText.textContent = "";

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    dom.dialogueText.textContent = fullDialogueText;
    dom.dialoguePanel.classList.remove("is-typing");
    return;
  }

  dom.dialoguePanel.classList.add("is-typing");
  typingTimer = window.setInterval(() => {
    typingIndex += 1;
    dom.dialogueText.textContent = fullDialogueText.slice(0, typingIndex);
    if (typingIndex >= fullDialogueText.length) finishTyping();
  }, 19);
}

function clearTyping() {
  if (typingTimer !== null) {
    window.clearInterval(typingTimer);
    typingTimer = null;
  }
}

function finishTyping() {
  clearTyping();
  typingIndex = fullDialogueText.length;
  dom.dialogueText.textContent = fullDialogueText;
  dom.dialoguePanel.classList.remove("is-typing");
}

function advanceDialogue() {
  if (typingTimer !== null) {
    finishTyping();
    return;
  }
  if (dialogueBusy) showNextDialogue();
}

